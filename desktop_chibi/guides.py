class GuideDialog(QDialog):
    def __init__(self, parent=None, topic='start'):
        super().__init__(parent)
        self.setWindowTitle('Путеводитель по Desktop Chibi')
        apply_theme(self)
        self.resize(700, 680)
        self.setMinimumSize(480, 400)
        layout = QVBoxLayout(self)
        layout.addWidget(window_bar('Помощь Desktop Chibi'))
        bar = SystemHeading('Помощь')
        layout.addWidget(bar)
        self.search = QLineEdit()
        self.search.setPlaceholderText('Найти: сообщения, кадры, вес, Discord…')
        layout.addWidget(self.search)
        self.topics = QComboBox()
        for key, (title, _) in GUIDES.items():
            self.topics.addItem(title, key)
        layout.addWidget(self.topics)
        self.browser = QTextBrowser()
        self.browser.setStyleSheet('padding: 14px;')
        self.browser.setOpenExternalLinks(True)
        layout.addWidget(self.browser, 1)
        buttons = QDialogButtonBox()
        buttons.addButton('Понятно', QDialogButtonBox.ButtonRole.AcceptRole)
        buttons.accepted.connect(self.accept)
        layout.addWidget(buttons)
        self.topics.currentIndexChanged.connect(self.render)
        self.search.textChanged.connect(self.find_topic)
        self.topics.setCurrentIndex(max(0, self.topics.findData(topic)))
        self.render()

    def render(self, *_):
        key = self.topics.currentData()
        if key in GUIDES:
            self.browser.setHtml(GUIDES[key][1])

    def find_topic(self, text):
        if not text.strip():
            return
        needle = text.strip().lower()
        match = next((key for key, (title, _) in GUIDES.items() if needle in title.lower()), None)
        if match is None:
            match = next((key for key, (_, body) in GUIDES.items() if needle in body.lower()), None)
        if match:
            self.topics.setCurrentIndex(self.topics.findData(match))
